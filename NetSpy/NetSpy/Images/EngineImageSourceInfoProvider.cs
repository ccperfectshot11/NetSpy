using System;
using System.Collections;
using System.Collections.Generic;
using System.Resources;
using NetSpy.Contracts.Images;

namespace NetSpy.Images {
	/// <summary>
	/// NetSpy: the NetSpy icons (Images\NetSpy\*.xaml, generated by Tools\NetSpy.Designer --convert-icons from the
	/// MIT licensed NetSpy SVGs) replace the NetSpy.Images images with the same name (ClassPrivate, Namespace...).
	/// NetSpy.Images is a NetSpyEx submodule, so it's left untouched; this provider is asked first (Order 0)
	/// and the default NetSpy.Images provider handles every other name.
	/// </summary>
	[ExportImageSourceInfoProvider(typeof(NetSpy.Images.Dummy), 0)]
	sealed class EngineImageSourceInfoProvider : IImageSourceInfoProvider {
		const string Prefix = "images/netspy/";
		readonly Dictionary<string, ImageSourceInfo[]> nameToInfos = LoadNames();

		public ImageSourceInfo[]? GetImageSourceInfos(string name) => nameToInfos.TryGetValue(name, out var infos) ? infos : null;

		static Dictionary<string, ImageSourceInfo[]> LoadNames() {
			var dict = new Dictionary<string, ImageSourceInfo[]>(StringComparer.OrdinalIgnoreCase);
			var assembly = typeof(EngineImageSourceInfoProvider).Assembly;
			var asmName = assembly.GetName();
			using var stream = assembly.GetManifestResourceStream(asmName.Name + ".g.resources");
			if (stream is null)
				return dict;
			var baseUri = "/" + asmName.Name + ";component/";
			using var reader = new ResourceReader(stream);
			foreach (DictionaryEntry entry in reader) {
				// the compiled xaml files are stored as "images/netspy/<name>.baml"
				if (entry.Key is not string key || !key.StartsWith(Prefix, StringComparison.OrdinalIgnoreCase) || !key.EndsWith(".baml", StringComparison.OrdinalIgnoreCase))
					continue;
				var path = key.Substring(0, key.Length - ".baml".Length);
				var name = path.Substring(Prefix.Length);
				dict[name] = new[] { new ImageSourceInfo { Uri = baseUri + path + ".xaml", Size = ImageSourceInfo.AnySize } };
			}
			return dict;
		}
	}
}
